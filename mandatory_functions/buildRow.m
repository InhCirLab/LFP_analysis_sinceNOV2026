function row = buildRow(nEpochs, durs, pow)
    if nEpochs == 0
        row = [0, 0, NaN, NaN, NaN, NaN, NaN, NaN, NaN, NaN, NaN, NaN, NaN, NaN, NaN];
        return;
    end
    row = [nEpochs, sum(durs), mean(durs), ...
        median(pow.rawT), median(pow.rawL), median(pow.rawH), ...
        median(pow.dbT),  median(pow.dbL),  median(pow.dbH),  ...
        mean(pow.zT),     mean(pow.zL),     mean(pow.zH),     ...
        median(pow.zmT),  median(pow.zmL),  median(pow.zmH)];
end